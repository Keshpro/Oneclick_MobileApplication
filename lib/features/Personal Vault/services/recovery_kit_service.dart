import 'dart:typed_data';

import 'package:file_saver/file_saver.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

class RecoveryKitService {
  final FirebaseAuth _auth = FirebaseAuth.instance;

  Future<void> createRecoveryKitPdf() async {
    final user = _auth.currentUser;

    if (user == null) {
      throw Exception('User is not signed in.');
    }

    final pdf = pw.Document();

    final createdAt = DateTime.now();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) {
          return [
            pw.Text(
              'OneClick Personal Vault',
              style: pw.TextStyle(
                fontSize: 22,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 6),
            pw.Text(
              'Emergency Recovery Kit',
              style: pw.TextStyle(
                fontSize: 18,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 20),

            _section(
              title: 'Account Information',
              children: [
                _row(
                  'User ID',
                  user.uid,
                ),
                _row(
                  'Email',
                  user.email ?? 'Not available',
                ),
                _row(
                  'Created',
                  createdAt.toLocal().toString(),
                ),
              ],
            ),

            pw.SizedBox(height: 18),

            _section(
              title: 'Vault Recovery Guidance',
              children: [
                pw.Bullet(
                  text:
                      'Sign in to OneClick using the same account used for this Personal Vault.',
                ),
                pw.Bullet(
                  text:
                      'Use your latest Personal Vault backup file if restoration is required.',
                ),
                pw.Bullet(
                  text:
                      'Keep backup files in a secure location that only you can access.',
                ),
                pw.Bullet(
                  text:
                      'Do not share this recovery kit publicly.',
                ),
              ],
            ),

            pw.SizedBox(height: 18),

            _section(
              title: 'Security Notes',
              children: [
                pw.Bullet(
                  text:
                      'Passwords, authentication secrets, biometric data, and recovery codes are not included in this document.',
                ),
                pw.Bullet(
                  text:
                      'This file is intended as recovery guidance only.',
                ),
                pw.Bullet(
                  text:
                      'For sensitive Vault data, use the secure backup or encrypted export features.',
                ),
              ],
            ),

            pw.SizedBox(height: 18),

            _section(
              title: 'Recovery Checklist',
              children: [
                _checkItem(
                  'Confirm access to your OneClick account.',
                ),
                _checkItem(
                  'Confirm access to your registered email account.',
                ),
                _checkItem(
                  'Locate your latest Personal Vault backup.',
                ),
                _checkItem(
                  'Verify that Vault documents are available after restoration.',
                ),
                _checkItem(
                  'Review your notification and security preferences.',
                ),
              ],
            ),

            pw.SizedBox(height: 30),

            pw.Divider(),

            pw.Text(
              'Generated by OneClick Personal Vault',
              style: const pw.TextStyle(
                fontSize: 10,
                color: PdfColors.grey700,
              ),
            ),
          ];
        },
      ),
    );

    final bytes = await pdf.save();

    final timestamp = DateTime.now()
        .toUtc()
        .toIso8601String()
        .replaceAll(':', '-')
        .replaceAll('.', '-');

    await FileSaver.instance.saveFile(
      name: 'oneclick_recovery_kit_$timestamp',
      bytes: Uint8List.fromList(bytes),
      fileExtension: 'pdf',
      mimeType: MimeType.pdf,
    );
  }

  pw.Widget _section({
    required String title,
    required List<pw.Widget> children,
  }) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(14),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(
          color: PdfColors.grey400,
        ),
        borderRadius: pw.BorderRadius.circular(8),
      ),
      child: pw.Column(
        crossAxisAlignment:
            pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            title,
            style: pw.TextStyle(
              fontSize: 14,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 10),
          ...children,
        ],
      ),
    );
  }

  pw.Widget _row(
    String label,
    String value,
  ) {
    return pw.Padding(
      padding:
          const pw.EdgeInsets.only(bottom: 6),
      child: pw.Row(
        crossAxisAlignment:
            pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 90,
            child: pw.Text(
              '$label:',
              style: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
          pw.Expanded(
            child: pw.Text(value),
          ),
        ],
      ),
    );
  }

  pw.Widget _checkItem(String text) {
    return pw.Padding(
      padding:
          const pw.EdgeInsets.only(bottom: 6),
      child: pw.Row(
        crossAxisAlignment:
            pw.CrossAxisAlignment.start,
        children: [
          pw.Text('[ ] '),
          pw.Expanded(
            child: pw.Text(text),
          ),
        ],
      ),
    );
  }
}